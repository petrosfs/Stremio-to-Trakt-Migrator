export type Lang = 'el' | 'en';
export const dictionaries: Record<Lang, Record<MsgKey, string>> = { el, en };

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const dict = dictionaries[lang] as Record<string, string>;
  let s = dict[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function detectLang(): Lang {
  const saved = load<Lang>('lang');
  if (saved === 'el' || saved === 'en') return saved;
  const nav = typeof navigator !== 'undefined' ? navigator.language || '' : '';
  return nav.toLowerCase().startsWith('el') ? 'el' : 'en';
}

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (key: MsgKey | string, vars?: Record<string, string | number>) => string };
const I18nContext = createContext<Ctx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(detectLang);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    save('lang', l);
    document.documentElement.lang = l;
  }, []);
  const value = useMemo<Ctx>(() => {
    if (typeof document !== 'undefined') document.documentElement.lang = lang;
    return { lang, setLang, t: (key, vars) => translate(lang, key, vars) };
  }, [lang, setLang]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): Ctx {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n outside provider');
  return ctx;
}
